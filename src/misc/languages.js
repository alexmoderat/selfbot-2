const LOOKUP = new Map();
for (const [code, ...names] of LANGUAGES) {
	LOOKUP.set(code, code);
	for (const n of names) if (!LOOKUP.has(n)) LOOKUP.set(n, code);
}

/** Sprachname, 2-/3-Buchstaben-Code oder Google-Code (zh-cn, zh-tw) -> Google-Code, sonst null. */
function resolveLanguage(input) {
	const key = String(input).trim().toLowerCase();
	if (!key) return null;
	return LOOKUP.get(key) ?? null;
}

